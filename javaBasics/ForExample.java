public class ForExample {
    public static void main(String[] args) {
        for (int i = 1; i <= 10; i++) {//executes 11 times
            System.out.println(i);//executes 10 times
     
        }
        int i = 1;
        while (i <= 10) {
            System.out.println(i);
            i++;
        }

    }
}
